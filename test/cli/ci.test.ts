import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import {
  ciEnabled,
  ciVariableName,
  ciVariables,
  mergeVariables,
  parseDotenv,
  parseShell,
  renderDotenv,
  renderShell,
  shellQuote,
} from "../../src/cli/ci-output.ts";
import { changesetText, FakeGitHub, setupProject, TOKEN } from "../flow/helpers.ts";
import { cli, fixtureRepo } from "./helpers.ts";

const read = (dir: string, name: string) => readFileSync(join(dir, name), "utf8");

describe("ci-output helpers", () => {
  it("names variables LAUNCHSET_ + upper snake case", () => {
    expect(ciVariableName("already-published")).toBe("LAUNCHSET_ALREADY_PUBLISHED");
    expect(ciVariableName("build-number")).toBe("LAUNCHSET_BUILD_NUMBER");
    expect(ciVariableName("release-sha")).toBe("LAUNCHSET_RELEASE_SHA");
    expect(ciVariableName("version")).toBe("LAUNCHSET_VERSION");
  });

  it("drops the plan, names outputs and lets env win", () => {
    expect(
      ciVariables(
        { plan: "{}", version: "1.0.0", "build-number": "7" },
        { LAUNCHSET_VERSION: "1.0.1", LAUNCHSET_CHANNEL: "release" },
      ),
    ).toEqual({
      LAUNCHSET_VERSION: "1.0.1",
      LAUNCHSET_BUILD_NUMBER: "7",
      LAUNCHSET_CHANNEL: "release",
    });
  });

  it("renders and parses dotenv without quotes", () => {
    const text = renderDotenv({ A: "1", B: "x=y z" });
    expect(text).toBe("A=1\nB=x=y z\n");
    expect(parseDotenv(text)).toEqual({ A: "1", B: "x=y z" });
    expect(renderDotenv({})).toBe("");
  });

  it("merges: replaced in place, new keys appended", () => {
    const merged = mergeVariables({ A: "1", B: "2" }, { C: "3", A: "9" });
    expect(Object.entries(merged)).toEqual([
      ["A", "9"],
      ["B", "2"],
      ["C", "3"],
    ]);
  });

  it("quotes for POSIX shells and round-trips", () => {
    expect(shellQuote("it's")).toBe(`'it'\\''s'`);
    const vars = { A: "it's", B: "line1\nline2", C: "" };
    const text = renderShell(vars);
    expect(text.startsWith("# Generated by launchset")).toBe(true);
    expect(parseShell(text)).toEqual(vars);
  });

  it("is on by default only on GitLab CI", () => {
    const io = (env: Record<string, string>) => ({ env }) as Parameters<typeof ciEnabled>[0];
    expect(ciEnabled(io({}), {})).toBe(false);
    expect(ciEnabled(io({ GITLAB_CI: "true" }), {})).toBe(true);
    expect(ciEnabled(io({ GITLAB_CI: "true" }), { ci: false })).toBe(false);
    expect(ciEnabled(io({}), { ci: true })).toBe(true);
  });
});

describe("--ci files", () => {
  it("merges stamp, verify and mark in one directory", async () => {
    const f = fixtureRepo();
    f.repo.git("config", "core.excludesFile", "/dev/null");
    writeFileSync(join(f.dir, ".git/info/exclude"), "plan.json\nlaunchset.env\nlaunchset.sh\n");
    const plan = (await cli(["plan", "--target", "ios", "--ci"], { cwd: f.dir })).stdout;
    expect(read(f.dir, "plan.json")).toBe(`${JSON.stringify(JSON.parse(plan))}\n`);

    const stamp = await cli(["stamp", "--target", "ios", "--plan", "@plan.json", "--ci"], {
      cwd: f.dir,
    });
    expect(stamp.code).toBe(0);
    const afterStamp = read(f.dir, "launchset.env");
    expect(afterStamp).toContain("LAUNCHSET_VERSION=1.4.0\n");
    expect(afterStamp).toContain("LAUNCHSET_CHANNEL=release\n");
    expect(afterStamp).not.toContain("LAUNCHSET_PLAN");

    const verify = await cli(["verify", "--target", "ios", "--plan", "@plan.json", "--ci"], {
      cwd: f.dir,
    });
    expect(verify.code).toBe(0);
    const mark = await cli(["mark", "--target", "ios", "--plan", "@plan.json", "--ci"], {
      cwd: f.dir,
    });
    expect(mark.code).toBe(0);

    const env = parseDotenv(read(f.dir, "launchset.env"));
    expect(env.LAUNCHSET_ALREADY_PUBLISHED).toBe("false");
    expect(env.LAUNCHSET_VERSION).toBe("1.4.0");
    expect(env.LAUNCHSET_BUILD_NUMBER).toMatch(/^\d+$/);
    expect(env.LAUNCHSET_RELEASE_SHA).toMatch(/^[0-9a-f]{40}$/);
    // Stamp's keys come first and keep their place.
    const keys = Object.keys(env);
    expect(keys.indexOf("LAUNCHSET_VERSION")).toBeLessThan(
      keys.indexOf("LAUNCHSET_ALREADY_PUBLISHED"),
    );
    for (const line of read(f.dir, "launchset.env").trimEnd().split("\n")) {
      expect(line).toMatch(/^[A-Z_]+=[^\r\n]*$/);
    }

    const shell = read(f.dir, "launchset.sh");
    expect(shell.split("\n")[0]).toMatch(/^# Generated by launchset/);
    expect(parseShell(shell)).toMatchObject(env);
    expect(shell).toContain("export LAUNCHSET_ALREADY_PUBLISHED='false'");
  });

  it("keeps multi-line values out of the dotenv file only", async () => {
    const f = fixtureRepo();
    const plan = await cli(["plan", "--target", "ios"], { cwd: f.dir });
    const doc = JSON.parse(plan.stdout);
    doc.targets.ios.docker = {
      images: ["a"],
      tags: ["1", "2"],
      refs: ["a:1", "a:2"],
      verifyTag: "1",
      labels: { k: "it's" },
    };
    const r = await cli(["stamp", "--target", "ios", "--plan", JSON.stringify(doc), "--ci"], {
      cwd: f.dir,
    });
    expect(r.code).toBe(0);
    expect(read(f.dir, "launchset.env")).not.toContain("DOCKER_TAGS");
    expect(read(f.dir, "launchset.env")).toContain("LAUNCHSET_DOCKER_REFS_JSON=");
    const shell = parseShell(read(f.dir, "launchset.sh"));
    expect(shell.LAUNCHSET_DOCKER_TAGS).toBe("a:1\na:2");
    expect(shell.LAUNCHSET_DOCKER_LABELS).toBe("k=it's");
  });

  it("honours the path variables and leaves plan.json alone without a plan", async () => {
    const f = fixtureRepo();
    mkdirSync(join(f.dir, "out"));
    writeFileSync(join(f.dir, "plan.json"), "keep\n");
    const env = {
      LAUNCHSET_DOTENV: "out/x.env",
      LAUNCHSET_SHELL_ENV: "out/x.sh",
      LAUNCHSET_PLAN_FILE: "out/p.json",
      NO_COLOR: "1",
    };
    const r = await cli(["mark", "--target", "web", "--version", "1.4.0", "--ci"], {
      cwd: f.dir,
      env,
    });
    expect(r.code).toBe(0);
    expect(read(f.dir, "out/x.env")).toContain("LAUNCHSET_VERSION=1.4.0\n");
    expect(read(f.dir, "out/x.sh")).toContain("export LAUNCHSET_VERSION='1.4.0'");
    expect(existsSync(join(f.dir, "out/p.json"))).toBe(false);
    expect(read(f.dir, "plan.json")).toBe("keep\n");
    expect(existsSync(join(f.dir, "launchset.env"))).toBe(false);
  });

  it("--no-ci writes nothing, even with GITLAB_CI", async () => {
    const f = fixtureRepo();
    const r = await cli(["mark", "--target", "web", "--version", "1.4.0", "--no-ci"], {
      cwd: f.dir,
      env: { GITLAB_CI: "true", NO_COLOR: "1" },
    });
    expect(r.code).toBe(0);
    expect(existsSync(join(f.dir, "launchset.env"))).toBe(false);
  });

  it("GITLAB_CI=true turns it on, and nothing is written otherwise", async () => {
    const f = fixtureRepo();
    const off = await cli(["mark", "--target", "web", "--version", "1.4.0"], { cwd: f.dir });
    expect(off.code).toBe(0);
    expect(existsSync(join(f.dir, "launchset.env"))).toBe(false);
    const on = await cli(["mark", "--target", "docker-api", "--version", "1.4.0"], {
      cwd: f.dir,
      env: { GITLAB_CI: "true", NO_COLOR: "1" },
    });
    expect(on.code).toBe(0);
    expect(read(f.dir, "launchset.env")).toContain("LAUNCHSET_VERSION=1.4.0\n");
  });

  it("prints the summary after the lines, or on stderr with --json", async () => {
    const f = fixtureRepo();
    const plain = await cli(["mark", "--target", "web", "--version", "1.4.0", "--ci"], {
      cwd: f.dir,
    });
    const summary = plain.stdout.split("\n\n")[1] ?? "";
    expect(summary).not.toBe("");
    const asJson = await cli(
      ["mark", "--target", "docker-api", "--version", "1.4.0", "--ci", "--json"],
      {
        cwd: f.dir,
      },
    );
    expect(JSON.parse(asJson.stdout)).toMatchObject({ version: "1.4.0" });
    expect(asJson.stderr).toContain("1.4.0");
  });

  it("warns when the dotenv file is over GitLab's limits", async () => {
    const f = fixtureRepo();
    writeFileSync(
      join(f.dir, "launchset.env"),
      `${Array.from({ length: 25 }, (_, i) => `OTHER_${i}=x`).join("\n")}\n`,
    );
    const r = await cli(["mark", "--target", "web", "--version", "1.4.0", "--ci"], { cwd: f.dir });
    expect(r.stderr).toContain("warning:");
    expect(r.stderr).toContain("at most 20 variables");
  });

  it("writes the files for verify", async () => {
    const f = fixtureRepo();
    const plan = (await cli(["plan", "--target", "ios"], { cwd: f.dir })).stdout;
    const r = await cli(["verify", "--target", "ios", "--plan", plan, "--ci"], { cwd: f.dir });
    expect(r.code).toBe(0);
    expect(existsSync(join(f.dir, "launchset.env"))).toBe(true);
  });
});

describe("release, preview-plan, preview-comment", () => {
  it("release opens the release PR and writes plan.json and the dotenv file", async () => {
    const project = setupProject();
    project.push("Add offline mode", {
      ".launchset/brave-lions-sing.md": changesetText("minor", "Add offline mode."),
    });
    const github = new FakeGitHub(project.remote);
    const r = await cli(["release", "--ci", "--repo", "acme/app", "--token", TOKEN], {
      cwd: project.repo.dir,
    });
    expect(r.code).toBe(0);
    expect(r.stdout).toContain("mode: release-pr");
    expect(github.openPrs()).toHaveLength(1);
    const env = parseDotenv(read(project.repo.dir, "launchset.env"));
    expect(env).toMatchObject({
      LAUNCHSET_MODE: "release-pr",
      LAUNCHSET_VERSION: "1.5.0",
      LAUNCHSET_PR_NUMBER: String(github.openPrs()[0]?.number),
    });
    expect(JSON.parse(read(project.repo.dir, "plan.json"))).toMatchObject({ mode: "release-pr" });
  });

  it("release without --ci writes no files", async () => {
    const project = setupProject();
    new FakeGitHub(project.remote);
    const r = await cli(["release", "--repo", "acme/app", "--token", TOKEN, "--json"], {
      cwd: project.repo.dir,
    });
    expect(r.code).toBe(0);
    expect(JSON.parse(r.stdout)).toMatchObject({ mode: "none" });
    expect(existsSync(join(project.repo.dir, "launchset.env"))).toBe(false);
  });

  it("plan --ci writes plan.json while stdout stays the plan", async () => {
    const f = fixtureRepo();
    const r = await cli(["plan", "--ci"], { cwd: f.dir });
    expect(JSON.parse(r.stdout)).toMatchObject({ mode: "none" });
    expect(JSON.parse(read(f.dir, "plan.json"))).toMatchObject({ mode: "none" });
    expect(read(f.dir, "launchset.env")).toContain("LAUNCHSET_MODE=none\n");
  });

  it("preview-comment with no plan has nothing to report", async () => {
    const f = fixtureRepo();
    const r = await cli(["preview-comment"], { cwd: f.dir });
    expect(r.code).toBe(0);
    expect(r.stdout.toLowerCase()).toContain("no preview plan was passed");
    const asJson = await cli(["preview-comment", "--plan", "", "--json"], { cwd: f.dir });
    expect(JSON.parse(asJson.stdout)).toMatchObject({ kind: "none" });
  });

  it("preview-plan plans a branch preview and writes the files", async () => {
    const f = fixtureRepo();
    f.repo.checkout("-b", "feature/x");
    f.repo.commit("work");
    const env = { GITHUB_RUN_NUMBER: "12", NO_COLOR: "1" };
    const r = await cli(["preview-plan", "--target", " , ", "--ci", "--no-fetch"], {
      cwd: f.dir,
      env,
    });
    expect(r.code).toBe(0);
    expect(JSON.parse(read(f.dir, "plan.json"))).toMatchObject({ channel: "preview" });
    const vars = parseDotenv(read(f.dir, "launchset.env"));
    expect(vars).toMatchObject({
      LAUNCHSET_CHANNEL: "preview",
      LAUNCHSET_PRERELEASE: "false",
      LAUNCHSET_VERSION: "1.4.1-feature-x.12",
    });
  });

  it("accepts nested GitLab repository paths", async () => {
    const f = fixtureRepo();
    const bad = await cli(["status", "--repo", "justone"], { cwd: f.dir });
    expect(bad.code).toBe(2);
    expect(bad.stderr).toContain("is not owner/repo");
    const nested = await cli(["status", "--repo", "group/sub/project"], { cwd: f.dir });
    expect(nested.stderr).not.toContain("is not owner/repo");
  });
});
