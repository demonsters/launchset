import { describe, expect, it } from "vitest";
import type { Plan } from "../../src/core/types.ts";
import { packageVersion } from "../../src/init/package-files.ts";
import {
  type ChildPipelineInput,
  checkTargetsFile,
  checkTemplateFile,
  inspectTargetJobs,
  renderChildPipeline,
} from "../../src/templates/gitlab-child.ts";
import { GitLabReference, parseGitLabYaml } from "../../src/templates/gitlab-yaml.ts";

interface Job {
  extends?: string;
  image?: string;
  stage?: string;
  when?: string;
  interruptible?: boolean;
  needs?: unknown[];
  variables?: Record<string, string>;
  before_script?: string[];
  script?: (string | GitLabReference)[];
}

type Child = Record<string, Job> & { include?: unknown; workflow?: unknown };

const SHA = "a".repeat(40);
const OTHER = "b".repeat(40);

function plan(overrides: Partial<Plan> = {}): Plan {
  return {
    schemaVersion: 1,
    mode: "publish",
    channel: "release",
    version: "1.5.0",
    baseVersion: "1.5.0",
    buildNumber: 217000000,
    releaseSha: SHA,
    branch: "main",
    maintenance: false,
    distTag: "latest",
    tag: "v1.5.0",
    matrix: ["api", "web"],
    targets: {},
    createdAt: "2026-11-18T12:00:00.000Z",
    ...overrides,
  };
}

function render(input: Partial<ChildPipelineInput> = {}) {
  const text = renderChildPipeline({
    plan: plan(),
    kind: "release",
    planJob: "launchset-release",
    currentSha: SHA,
    ...input,
  });
  return { text, doc: parseGitLabYaml(text) as Child };
}

const job = (doc: Child, name: string): Job => {
  const found = doc[name];
  if (!found) throw new Error(`no job ${name} in ${Object.keys(doc).join(", ")}`);
  return found;
};

const fromParent = (planJob: string) => ({ pipeline: "$PARENT_PIPELINE_ID", job: planJob });

describe("renderChildPipeline", () => {
  it("publish: one build job per target, then finalize", () => {
    const { text, doc } = render();
    expect(Object.keys(doc)).toEqual([
      "workflow",
      "include",
      ".launchset_cli",
      "build-api",
      "build-web",
      "launchset-finalize",
    ]);
    expect(doc.include).toEqual([{ local: ".gitlab/launchset-targets.yml" }]);
    expect(text).toMatch(/^# Generated by launchset .+ for the release of 1\.5\.0 \(api, web\)\./);

    const web = job(doc, "build-web");
    expect(web.extends).toBe(".launchset-web");
    expect(web.stage).toBe("test");
    expect(web.needs).toEqual([fromParent("launchset-release")]);
    expect(web.interruptible).toBe(false);
    expect(web.variables).toEqual({ LAUNCHSET_CLI: `launchset@${packageVersion()}` });
    const script = web.script ?? [];
    const lines = script.filter((line): line is string => typeof line === "string");
    expect(lines[0]).toBe('cd "$CI_PROJECT_DIR"');
    expect(lines).toContain(
      'command -v launchset >/dev/null 2>&1 || npm install --global --no-fund --no-audit --loglevel=error "$LAUNCHSET_CLI"',
    );
    expect(lines.slice(3)).toEqual([
      "launchset stamp --target web --plan @plan.json --ci",
      ". ./launchset.sh",
      "launchset verify --target web --plan @plan.json --ci",
      ". ./launchset.sh",
      'if [ "${LAUNCHSET_ALREADY_PUBLISHED:-}" = "true" ]; then launchset mark --target web --plan @plan.json --ci; exit $?; fi',
      'cd "$CI_PROJECT_DIR"',
      "launchset mark --target web --plan @plan.json --ci",
    ]);
    // The user's steps, as a !reference tag, between the verify and mark lines.
    const reference = script.find((line) => line instanceof GitLabReference);
    expect(reference).toEqual(new GitLabReference([".launchset-web", "script"]));
    expect(script.indexOf(reference as GitLabReference)).toBe(script.length - 3);
    expect(text).toContain("- !reference [.launchset-web, script]");
    // No checkout: the pipeline's commit is the release commit.
    expect(text).not.toContain("git checkout");
    expect(text).not.toContain('GIT_DEPTH: "0"\n  script');

    const finalize = job(doc, "launchset-finalize");
    expect(finalize.extends).toBe(".launchset_cli");
    expect(finalize.when).toBe("always");
    expect(finalize.needs).toEqual([
      fromParent("launchset-release"),
      { job: "build-api", artifacts: false },
      { job: "build-web", artifacts: false },
    ]);
    expect(finalize.script).toEqual(["launchset finalize --plan @plan.json --ci"]);
    expect(job(doc, ".launchset_cli").variables?.GIT_DEPTH).toBe("0");
    expect(job(doc, ".launchset_cli").image).toBe("node:24");
  });

  // Jobs without rules get GitLab's default only: [branches, tags], and an MR pipeline's ref
  // (refs/merge-requests/<iid>/head) is neither: without workflow rules, which drop that default,
  // GitLab couldn't create the child of an MR pipeline (downstream_pipeline_creation_failed).
  it.each([
    ["a release", {}],
    ["nothing to build", { plan: plan({ mode: "none", matrix: [] }) }],
    [
      "a preview",
      {
        plan: plan({ mode: "preview", channel: "preview", matrix: ["web"] }),
        kind: "preview",
        planJob: "launchset-preview-plan",
      },
    ],
    ["a skipped preview", { plan: undefined, kind: "preview", planJob: "launchset-preview-plan" }],
  ] as const)("%s: workflow rules that keep every job, also in an MR pipeline", (_, input) => {
    const { doc } = render(input as Partial<ChildPipelineInput>);
    expect(Object.keys(doc)[0]).toBe("workflow");
    expect(doc.workflow).toEqual({ rules: [{ when: "always" }] });
    for (const [name, j] of Object.entries(doc as Record<string, Job & { rules?: unknown }>)) {
      if (name === "workflow" || name === "include") continue;
      expect(j.rules, name).toBeUndefined();
    }
  });

  it("puts every job in stage test, which a child pipeline always has", () => {
    const stages = (doc: Child) =>
      Object.entries(doc as Record<string, Job>)
        .filter(([name]) => name !== "include" && name !== "workflow")
        .map(([name, j]) => [name, j.stage ?? (j.extends === ".launchset_cli" ? "(cli)" : "")]);
    expect(stages(render().doc)).toEqual([
      [".launchset_cli", "test"],
      ["build-api", "test"],
      ["build-web", "test"],
      ["launchset-finalize", "(cli)"],
    ]);
    const nothing = render({ plan: plan({ mode: "none", matrix: [] }) }).doc;
    expect(job(nothing, "launchset-nothing-to-build").stage).toBe("test");
  });

  it("ship of one manual target: its build job and finalize", () => {
    const { text, doc } = render({ plan: plan({ mode: "ship", matrix: ["ios"] }) });
    expect(Object.keys(doc)).toEqual([
      "workflow",
      "include",
      ".launchset_cli",
      "build-ios",
      "launchset-finalize",
    ]);
    expect(text).toContain("for shipping 1.5.0 (ios)");
    expect(job(doc, "launchset-finalize").needs).toEqual([
      fromParent("launchset-release"),
      { job: "build-ios", artifacts: false },
    ]);
  });

  it("publish with an empty matrix: only finalize (it still creates the release)", () => {
    const { doc } = render({ plan: plan({ matrix: [] }) });
    expect(Object.keys(doc)).toEqual(["workflow", ".launchset_cli", "launchset-finalize"]);
    expect(job(doc, "launchset-finalize").needs).toEqual([fromParent("launchset-release")]);
  });

  it.each([
    ["release-pr", "The release MR for 1.6.0 is up to date"],
    ["none", "Nothing to release"],
  ] as const)("%s: a single nothing-to-build job that says why", (mode, why) => {
    const { doc } = render({
      plan: plan({
        mode,
        matrix: [],
        releaseSha: "",
        ...(mode === "release-pr"
          ? { releasePr: { version: "1.6.0", bump: "minor", changesets: [], botPrs: [] } }
          : {}),
      }),
    });
    expect(Object.keys(doc)).toEqual(["workflow", "launchset-nothing-to-build"]);
    const nothing = job(doc, "launchset-nothing-to-build");
    expect(nothing.image).toBe("busybox:1");
    expect(nothing.variables).toEqual({ GIT_STRATEGY: "none" });
    expect(nothing.script?.[0]).toMatch(new RegExp(`^echo '${why}`));
  });

  it("preview: preview-<target> jobs with stamp only, interruptible, no finalize", () => {
    const { text, doc } = render({
      plan: plan({
        mode: "preview",
        channel: "preview",
        version: "1.5.0-pr.3.17",
        matrix: ["web"],
      }),
      kind: "preview",
      planJob: "launchset-preview-plan",
    });
    expect(Object.keys(doc)).toEqual([
      "workflow",
      "include",
      ".launchset_cli",
      "preview-web",
      "launchset-preview-comment",
    ]);
    const web = job(doc, "preview-web");
    expect(web.needs).toEqual([fromParent("launchset-preview-plan")]);
    expect(web.interruptible).toBe(true);
    expect(text).toContain("launchset stamp --target web");
    expect(text).not.toContain("launchset verify");
    expect(text).not.toContain("launchset mark");
    expect(web.script?.at(-1)).toEqual(new GitLabReference([".launchset-web", "script"]));
    expect(text).toContain("for the preview 1.5.0-pr.3.17 (web)");
  });

  it("preview: launchset-preview-comment last, always, after every preview job", () => {
    const { doc } = render({
      plan: plan({ mode: "preview", channel: "preview", matrix: ["api", "web"] }),
      kind: "preview",
      planJob: "launchset-preview-plan",
    });
    expect(Object.keys(doc).at(-1)).toBe("launchset-preview-comment");
    const comment = job(doc, "launchset-preview-comment");
    expect(comment.extends).toBe(".launchset_cli");
    expect(comment.when).toBe("always");
    expect(comment.interruptible).toBe(true);
    expect(comment.needs).toEqual([
      fromParent("launchset-preview-plan"),
      { job: "preview-api", artifacts: false },
      { job: "preview-web", artifacts: false },
    ]);
    expect(comment.script).toEqual(["launchset preview-comment --plan @plan.json --ci"]);
    expect(job(doc, ".launchset_cli").variables?.GIT_DEPTH).toBe("0");
  });

  it("a preview plan without targets: only the comment job, which reports it", () => {
    const { doc } = render({
      plan: plan({ mode: "preview", channel: "preview", matrix: [] }),
      kind: "preview",
      planJob: "launchset-preview-plan",
    });
    expect(Object.keys(doc)).toEqual(["workflow", ".launchset_cli", "launchset-preview-comment"]);
    expect(job(doc, "launchset-preview-comment").needs).toEqual([
      fromParent("launchset-preview-plan"),
    ]);
  });

  it("prerelease previews are never interruptible (they reserved a tag)", () => {
    const { doc } = render({
      plan: plan({ mode: "preview", channel: "prerelease", matrix: ["web"] }),
      kind: "preview",
      planJob: "launchset-preview-plan",
    });
    expect(job(doc, "preview-web").interruptible).toBe(false);
    expect(job(doc, "launchset-preview-comment").interruptible).toBe(false);
  });

  it("a skipped preview: nothing to build, with the reason, and no comment job", () => {
    const { doc } = render({
      plan: undefined,
      kind: "preview",
      planJob: "launchset-preview-plan",
      reason: "MR !3 doesn't have the `launchset:preview` label: add it, or run the manual job.",
    });
    expect(Object.keys(doc)).toEqual(["workflow", "launchset-nothing-to-build"]);
    expect(job(doc, "launchset-nothing-to-build").script).toEqual([
      "echo 'MR !3 doesn'\\''t have the `launchset:preview` label: add it, or run the manual job.'",
    ]);
  });

  it("release-sha differs from the pipeline's commit: check it out, with full history", () => {
    const { text, doc } = render({ currentSha: OTHER });
    for (const name of ["build-api", "build-web"]) {
      const built = job(doc, name);
      expect(built.variables?.GIT_DEPTH).toBe("0");
      const lines = built.script?.filter((l) => typeof l === "string") ?? [];
      const checkout = lines.indexOf(`git checkout --quiet --detach ${SHA}`);
      expect(checkout).toBeGreaterThan(0);
      expect(checkout).toBeLessThan(
        lines.indexOf(`launchset stamp --target ${name.slice(6)} --plan @plan.json --ci`),
      );
    }
    expect(job(doc, "launchset-finalize").script).toEqual([
      `git checkout --quiet --detach ${SHA}`,
      "launchset finalize --plan @plan.json --ci",
    ]);
    expect(text.match(/git checkout/g)).toHaveLength(3);
  });

  it("rejects a release-sha that isn't a commit", () => {
    expect(() =>
      render({ plan: plan({ releaseSha: "main; rm -rf /" }), currentSha: OTHER }),
    ).toThrow(/is not a commit/);
  });

  it("quotes odd target names in job names, !reference keys and shell words", () => {
    const name = "we'b: x #1";
    const { text, doc } = render({ plan: plan({ matrix: [name, "123", "true"] }) });
    const built = job(doc, `build-${name}`);
    expect(built.extends).toBe(`.launchset-${name}`);
    expect(built.script).toContainEqual(new GitLabReference([`.launchset-${name}`, "script"]));
    expect(built.script).toContain(
      `launchset stamp --target 'we'\\''b: x #1' --plan @plan.json --ci`,
    );
    expect(job(doc, "build-123").extends).toBe(".launchset-123");
    expect(job(doc, "build-true").script).toContainEqual(
      new GitLabReference([".launchset-true", "script"]),
    );
    expect(job(doc, "launchset-finalize").needs).toContainEqual({
      job: `build-${name}`,
      artifacts: false,
    });
    expect(text).toContain(`- !reference [".launchset-we'b: x #1", script]`);
  });

  it("passes LAUNCHSET_CLI and the targets file on", () => {
    const { doc } = render({ cliSpec: "./launchset.tgz", targetsFile: "ci/targets.yml" });
    expect(doc.include).toEqual([{ local: "ci/targets.yml" }]);
    expect(job(doc, "build-web").variables?.LAUNCHSET_CLI).toBe("./launchset.tgz");
    expect(job(doc, ".launchset_cli").variables?.LAUNCHSET_CLI).toBe("./launchset.tgz");
  });
});

describe("checkTargetsFile", () => {
  const good = [
    ".launchset-web:",
    "  image: node:24",
    "  script:",
    "    - npm run build",
    "    - !reference [.common, script]",
    ".launchset-api:",
    "  extends: .docker",
  ].join("\n");

  it("accepts a job with a script or extends per target (and !reference tags)", () => {
    expect(checkTargetsFile(good, ["web", "api"])).toEqual([]);
  });

  it("does nothing when there is nothing to build", () => {
    expect(checkTargetsFile(undefined, [])).toEqual([]);
  });

  it("fails clearly when the file is missing", () => {
    expect(() => checkTargetsFile(undefined, ["web"])).toThrow(
      expect.objectContaining({
        code: "gitlab-targets-missing",
        message: expect.stringContaining(".gitlab/launchset-targets.yml doesn't exist"),
        hint: expect.stringContaining(".launchset-<target>"),
      }),
    );
  });

  it("fails for a target without a job or without a script", () => {
    expect(() => checkTargetsFile(good, ["web", "ios"])).toThrow(
      /has no job \.launchset-ios \(target ios\)/,
    );
    expect(() => checkTargetsFile(".launchset-web:\n  image: node:24\n", ["web"])).toThrow(
      /\.launchset-web \(target web\) with a script/,
    );
  });

  it("fails for invalid YAML", () => {
    expect(() => checkTargetsFile(".launchset-web: [", ["web"])).toThrow(/is not valid YAML/);
  });

  it("only warns when the job may come from the file's includes", () => {
    const text = "include:\n  - local: ci/more.yml\n";
    expect(checkTargetsFile(text, ["web"])).toEqual([
      ".gitlab/launchset-targets.yml doesn't define .launchset-web itself; it has to come from one of its includes.",
    ]);
  });
});

const strings = (j: Job) => (j.script ?? []).filter((l): l is string => typeof l === "string");

describe("renderChildPipeline: PowerShell targets (gitlab.shell)", () => {
  const check = "if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }";

  it("writes launchset's lines in PowerShell, checking $LASTEXITCODE after each command", () => {
    const { doc, text } = render({
      plan: plan({ matrix: ["windows", "web"] }),
      targets: { windows: { shell: "powershell" } },
      currentSha: OTHER,
    });
    const windows = job(doc, "build-windows");
    expect(strings(windows)).toEqual([
      "Set-Location -LiteralPath $env:CI_PROJECT_DIR",
      `if (-not (Get-Command launchset -ErrorAction SilentlyContinue)) { npm install --global --no-fund --no-audit --loglevel=error "$env:LAUNCHSET_CLI"; ${check} }`,
      'if (-not (Get-Command launchset -ErrorAction SilentlyContinue)) { $env:Path = "$(npm prefix --global);$env:Path" }',
      `launchset --version; ${check}`,
      `git checkout --quiet --detach ${SHA}; ${check}`,
      `launchset stamp --target windows --plan '@plan.json' --ci; ${check}`,
      ". ./launchset.ps1",
      `launchset verify --target windows --plan '@plan.json' --ci; ${check}`,
      ". ./launchset.ps1",
      "if ($env:LAUNCHSET_ALREADY_PUBLISHED -eq 'true') { launchset mark --target windows --plan '@plan.json' --ci; exit $LASTEXITCODE }",
      "Set-Location -LiteralPath $env:CI_PROJECT_DIR",
      `launchset mark --target windows --plan '@plan.json' --ci; ${check}`,
    ]);
    expect(windows.script).toContainEqual(new GitLabReference([".launchset-windows", "script"]));
    // No sh syntax in the PowerShell job.
    const block = text.slice(text.indexOf("build-windows:"), text.indexOf("build-web:"));
    expect(block).not.toMatch(
      /\[ -n|command -v|\$\{|\. \.\/launchset\.sh|"\$CI_PROJECT_DIR"|@plan\.json(?!')/,
    );
    expect(block).toContain("# PowerShell (gitlab.shell)");
    // Other targets keep sh.
    expect(strings(job(doc, "build-web"))[0]).toBe('cd "$CI_PROJECT_DIR"');
  });

  it("previews: stamp only, in PowerShell too", () => {
    const { doc } = render({
      plan: plan({ mode: "preview", channel: "preview", matrix: ["windows"] }),
      kind: "preview",
      planJob: "launchset-preview-plan",
      targets: { windows: { shell: "powershell" } },
    });
    const lines = strings(job(doc, "preview-windows"));
    expect(lines).toContain(`launchset stamp --target windows --plan '@plan.json' --ci; ${check}`);
    expect(lines.at(-1)).toBe(". ./launchset.ps1");
    expect(lines.join("\n")).not.toContain("launchset mark");
  });

  it("quotes odd target names for PowerShell", () => {
    const name = "we'b x’1";
    const { doc } = render({
      plan: plan({ matrix: [name] }),
      targets: { [name]: { shell: "powershell" } },
    });
    expect(strings(job(doc, `build-${name}`))).toContain(
      `launchset stamp --target 'we''b x’’1' --plan '@plan.json' --ci; ${check}`,
    );
  });
});

describe("renderChildPipeline: after", () => {
  const after = { site: { after: ["windows", "appimage"] } };

  it("needs the jobs of the targets it comes after, optional, with their artifacts", () => {
    const { doc, text } = render({
      plan: plan({ matrix: ["windows", "appimage", "site"] }),
      targets: after,
    });
    expect(job(doc, "build-site").needs).toEqual([
      fromParent("launchset-release"),
      { job: "build-windows", artifacts: true, optional: true },
      { job: "build-appimage", artifacts: true, optional: true },
    ]);
    expect(text).toContain("# after: windows, appimage.");
    expect(job(doc, "build-windows").needs).toEqual([fromParent("launchset-release")]);
  });

  it("a retry that builds only the dependent target: no needs on jobs that aren't there", () => {
    const { doc, text } = render({ plan: plan({ matrix: ["site"] }), targets: after });
    expect(job(doc, "build-site").needs).toEqual([fromParent("launchset-release")]);
    expect(text).toContain("# (windows isn't built in this pipeline.)");
  });

  it("previews need the preview jobs", () => {
    const { doc } = render({
      plan: plan({ mode: "preview", channel: "preview", matrix: ["windows", "site"] }),
      kind: "preview",
      planJob: "launchset-preview-plan",
      targets: after,
    });
    expect(job(doc, "preview-site").needs).toEqual([
      fromParent("launchset-preview-plan"),
      { job: "preview-windows", artifacts: true, optional: true },
    ]);
  });
});

