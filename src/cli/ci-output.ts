/**
 * `--ci` output mode: a CI runner without `@actions/core` gets a command's outputs and exported
 * variables as files. `plan.json` holds the plan, `launchset.env` is a GitLab dotenv report
 * (`artifacts:reports:dotenv`) and `launchset.sh` is the same variables for `. ./launchset.sh`.
 * Several commands in one job merge into the same files. The pure helpers come first.
 */

import { existsSync } from "node:fs";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import type { FlowContext, FlowResult, Logger } from "../flow/index.ts";
import { outputsFor } from "../flow/index.ts";
import type { CliIo } from "./io.ts";
import { emit, type GlobalOpts } from "./run.ts";

/** GitLab's dotenv report limits (the self-managed defaults): 5 KB and 20 variables. */
export const DOTENV_MAX_BYTES = 5 * 1024;
export const DOTENV_MAX_VARIABLES = 20;

export const DEFAULT_PLAN_FILE = "plan.json";
export const DEFAULT_DOTENV_FILE = "launchset.env";
export const DEFAULT_SHELL_FILE = "launchset.sh";

const SHELL_HEADER = "# Generated by launchset (--ci). Source it: . ./launchset.sh";

/** `already-published` → `LAUNCHSET_ALREADY_PUBLISHED`. */
export function ciVariableName(output: string): string {
  return `LAUNCHSET_${output
    .replace(/[^A-Za-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "")
    .toUpperCase()}`;
}

/**
 * The variables of a result: every output except `plan` (it goes to plan.json) under its
 * `LAUNCHSET_*` name, then the result's `env` as is (it wins on a clash).
 */
export function ciVariables(
  outputs: Record<string, string>,
  env: Record<string, string> = {},
): Record<string, string> {
  const variables: Record<string, string> = {};
  for (const [name, value] of Object.entries(outputs)) {
    if (name === "plan") continue;
    variables[ciVariableName(name)] = value;
  }
  for (const [name, value] of Object.entries(env)) variables[name] = value;
  return variables;
}

/** A value that can't go in a dotenv file: it has a line break. */
export function dotenvUnsafe(value: string): boolean {
  return /[\r\n]/.test(value);
}

/** `NAME=value` lines, no quotes, no comments. Values with a line break must be filtered first. */
export function renderDotenv(variables: Record<string, string>): string {
  const lines = Object.entries(variables).map(([name, value]) => `${name}=${value}`);
  return lines.length === 0 ? "" : `${lines.join("\n")}\n`;
}

/** Parse a dotenv file (first `=` splits; blank and `#` lines are ignored). */
export function parseDotenv(text: string): Record<string, string> {
  const variables: Record<string, string> = {};
  for (const line of text.split(/\r?\n/)) {
    if (line.trim() === "" || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq <= 0) continue;
    variables[line.slice(0, eq)] = line.slice(eq + 1);
  }
  return variables;
}

/** Merge: existing keys keep their place (replaced in place), new keys are appended. */
export function mergeVariables(
  existing: Record<string, string>,
  next: Record<string, string>,
): Record<string, string> {
  return { ...existing, ...next };
}

/** POSIX single quoting: `it's` → `'it'\''s'`. */
export function shellQuote(value: string): string {
  return `'${value.replaceAll("'", `'\\''`)}'`;
}

/** The shell file: a header comment and one `export NAME='value'` per variable. */
export function renderShell(variables: Record<string, string>): string {
  const lines = Object.entries(variables).map(
    ([name, value]) => `export ${name}=${shellQuote(value)}`,
  );
  return `${SHELL_HEADER}\n${lines.length > 0 ? `${lines.join("\n")}\n` : ""}`;
}

/** Parse a file `renderShell` wrote (values may span lines). */
export function parseShell(text: string): Record<string, string> {
  const variables: Record<string, string> = {};
  const pattern = /^export ([A-Za-z_][A-Za-z0-9_]*)='((?:[^']|'\\'')*)'$/gm;
  for (const match of text.matchAll(pattern)) {
    variables[match[1] as string] = (match[2] as string).replaceAll("'\\''", "'");
  }
  return variables;
}

/** Whether `--ci` is on: the flag, else `GITLAB_CI=true`. */
export function ciEnabled(io: CliIo, opts: { ci?: boolean | undefined }): boolean {
  return opts.ci ?? io.env.GITLAB_CI === "true";
}

async function readIfExists(path: string): Promise<string> {
  return existsSync(path) ? readFile(path, "utf8") : "";
}

/**
 * Write plan.json, the dotenv file and the shell file for one command's result (merging with
 * what earlier commands of the job wrote).
 */
export async function writeCiFiles(
  io: CliIo,
  log: Logger,
  outputs: Record<string, string>,
  env: Record<string, string> | undefined,
): Promise<void> {
  const file = (variable: string, fallback: string) =>
    resolve(io.cwd, io.env[variable]?.trim() || fallback);

  const plan = outputs.plan;
  if (plan !== undefined && plan !== "") {
    await writeFile(file("LAUNCHSET_PLAN_FILE", DEFAULT_PLAN_FILE), `${plan}\n`, "utf8");
  }

  const variables = ciVariables(outputs, env);

  const shellPath = file("LAUNCHSET_SHELL_ENV", DEFAULT_SHELL_FILE);
  const shell = mergeVariables(parseShell(await readIfExists(shellPath)), variables);
  await writeFile(shellPath, renderShell(shell), "utf8");

  const dotenvPath = file("LAUNCHSET_DOTENV", DEFAULT_DOTENV_FILE);
  const safe: Record<string, string> = {};
  const stale: string[] = [];
  for (const [name, value] of Object.entries(variables)) {
    if (dotenvUnsafe(value)) {
      log.debug(`${name} has a line break: left out of ${dotenvPath} (it is in ${shellPath})`);
      stale.push(name);
    } else {
      safe[name] = value;
    }
  }
  const existing = parseDotenv(await readIfExists(dotenvPath));
  for (const name of stale) delete existing[name];
  const dotenv = mergeVariables(existing, safe);
  const text = renderDotenv(dotenv);
  await writeFile(dotenvPath, text, "utf8");

  const count = Object.keys(dotenv).length;
  const bytes = Buffer.byteLength(text, "utf8");
  if (bytes > DOTENV_MAX_BYTES || count > DOTENV_MAX_VARIABLES) {
    log.warn(
      `${dotenvPath} has ${count} variables and ${bytes} bytes; GitLab accepts at most ${DOTENV_MAX_VARIABLES} variables and ${DOTENV_MAX_BYTES / 1024} KB in a dotenv report`,
    );
  }
}

export interface FinishOptions {
  json?: boolean | undefined;
  ci?: boolean | undefined;
  /** Stdout carries the command's own data (`plan`): the summary always goes to stderr. */
  summaryToStderr?: boolean;
}

/** Write the CI files and print the job summary (after the result lines, a blank line apart). */
export async function finishCi(
  io: CliIo,
  log: Logger,
  command: string,
  result: FlowResult,
  context: FlowContext,
  opts: FinishOptions,
): Promise<void> {
  if (!ciEnabled(io, opts)) return;
  await writeCiFiles(io, log, outputsFor(command, result, context), result.env);
  const summary = result.summary.trim();
  if (summary === "") return;
  const toStderr = opts.json || opts.summaryToStderr;
  const hasLines = result.lines.length > 0 && !(opts.json && result.ok);
  const text = `${hasLines ? "\n" : ""}${summary}\n`;
  if (toStderr) io.stderr(text);
  else io.stdout(text);
}

/** `emit` plus the `--ci` output. */
export async function emitCi(
  io: CliIo,
  log: Logger,
  command: string,
  result: FlowResult,
  context: FlowContext,
  opts: GlobalOpts,
): Promise<number> {
  const code = emit(io, result, { json: opts.json });
  await finishCi(io, log, command, result, context, opts);
  return code;
}
