/** GitLab's dotenv report limits (the self-managed defaults): 5 KB and 20 variables. */
export const DOTENV_MAX_BYTES = 5 * 1024;
export const DOTENV_MAX_VARIABLES = 20;

/**
 * The commands whose launchset.env the generated templates upload as a dotenv report
 * (`launchset-release`): only there do GitLab's limits matter. Elsewhere (the child's build
 * jobs, where stamp, verify and mark add up to more variables) going over is a debug note.
 */
export const DOTENV_REPORT_COMMANDS: ReadonlySet<string> = new Set(["release"]);

export { ciEnabled } from "./ci-files.ts";

const SHELL_HEADER = "# Generated by launchset (--ci). Source it: . ./launchset.sh";
const POWERSHELL_HEADER = "# Generated by launchset (--ci). Load it: . ./launchset.ps1";

/** `already-published` → `LAUNCHSET_ALREADY_PUBLISHED`. */
export function ciVariableName(output: string): string {
  return `LAUNCHSET_${output
    .replace(/[^A-Za-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "")
    .toUpperCase()}`;
}

/**
 * The variables of a result: every output except `plan` (it goes to plan.json) under its
 * `LAUNCHSET_*` name, then the result's `env` as is (it wins on a clash).
 */
export function ciVariables(
  outputs: Record<string, string>,
  env: Record<string, string> = {},
): Record<string, string> {
  const variables: Record<string, string> = {};
  for (const [name, value] of Object.entries(outputs)) {
    if (name === "plan") continue;
    variables[ciVariableName(name)] = value;
  }
  for (const [name, value] of Object.entries(env)) variables[name] = value;
  return variables;
}

/** A value that can't go in a dotenv file: it has a line break. */
export function dotenvUnsafe(value: string): boolean {
  return /[\r\n]/.test(value);
}

/** `NAME=value` lines, no quotes, no comments. Values with a line break must be filtered first. */
export function renderDotenv(variables: Record<string, string>): string {
  const lines = Object.entries(variables).map(([name, value]) => `${name}=${value}`);
  return lines.length === 0 ? "" : `${lines.join("\n")}\n`;
}

/** Parse a dotenv file (first `=` splits; blank and `#` lines are ignored). */
export function parseDotenv(text: string): Record<string, string> {
  const variables: Record<string, string> = {};
  for (const line of text.split(/\r?\n/)) {
    if (line.trim() === "" || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq <= 0) continue;
    variables[line.slice(0, eq)] = line.slice(eq + 1);
  }
  return variables;
}

/** Merge: existing keys keep their place (replaced in place), new keys are appended. */
export function mergeVariables(
  existing: Record<string, string>,
  next: Record<string, string>,
): Record<string, string> {
  return { ...existing, ...next };
}

/** POSIX single quoting: `it's` → `'it'\''s'`. */
export function shellQuote(value: string): string {
  return `'${value.replaceAll("'", `'\\''`)}'`;
}

/** The shell file: a header comment and one `export NAME='value'` per variable. */
export function renderShell(variables: Record<string, string>): string {
  const lines = Object.entries(variables).map(
    ([name, value]) => `export ${name}=${shellQuote(value)}`,
  );
  return `${SHELL_HEADER}\n${lines.length > 0 ? `${lines.join("\n")}\n` : ""}`;
}

/** Parse a file `renderShell` wrote (values may span lines). */
export function parseShell(text: string): Record<string, string> {
  const variables: Record<string, string> = {};
  const pattern = /^export ([A-Za-z_][A-Za-z0-9_]*)='((?:[^']|'\\'')*)'$/gm;
  for (const match of text.matchAll(pattern)) {
    variables[match[1] as string] = (match[2] as string).replaceAll("'\\''", "'");
  }
  return variables;
}

/**
 * The PowerShell file: a header comment and one `$env:NAME = 'value'` per variable. Single
 * quotes don't expand anything; quote characters (also PowerShell's typographic ones) are
 * doubled. Written with a byte order mark: Windows PowerShell 5.1 reads a file without one in
 * the system's code page, which would garble non-ASCII values.
 */
export function renderPowerShell(variables: Record<string, string>): string {
  const lines = Object.entries(variables).map(
    ([name, value]) => `$env:${name} = ${psQuote(value)}`,
  );
  return `\uFEFF${POWERSHELL_HEADER}\n${lines.length > 0 ? `${lines.join("\n")}\n` : ""}`;
}

async function readIfExists(path: string): Promise<string> {
  return existsSync(path) ? readFile(path, "utf8") : "";
}

/**
 * Write plan.json, the dotenv file and the shell file for one command's result (merging with
 * what earlier commands of the job wrote). With `report`, a dotenv file over GitLab's limits is
 * a warning (it is uploaded as a dotenv report), else a debug note.
 */
export async function writeCiFiles(
  io: CliIo,
  log: Logger,
  outputs: Record<string, string>,
  env: Record<string, string> | undefined,
  options: { report?: boolean } = {},
): Promise<void> {
  const plan = outputs.plan;
  if (plan !== undefined && plan !== "") {
    await writeFile(ciFilePath(io, "plan"), `${plan}\n`, "utf8");
  }

  const variables = ciVariables(outputs, env);

  const shellPath = ciFilePath(io, "shell");
  const shell = mergeVariables(parseShell(await readIfExists(shellPath)), variables);
  await writeFile(shellPath, renderShell(shell), "utf8");
  // The same variables for PowerShell runners (launchset.sh holds the merged set).
  await writeFile(ciFilePath(io, "powershell"), renderPowerShell(shell), "utf8");

  const dotenvPath = ciFilePath(io, "dotenv");
  const safe: Record<string, string> = {};
  const stale: string[] = [];
  for (const [name, value] of Object.entries(variables)) {
    if (dotenvUnsafe(value)) {
      log.debug(`${name} has a line break: left out of ${dotenvPath} (it is in ${shellPath})`);
      stale.push(name);
    } else {
      safe[name] = value;
    }
  }
  const existing = parseDotenv(await readIfExists(dotenvPath));
  for (const name of stale) delete existing[name];
  const dotenv = mergeVariables(existing, safe);
  const text = renderDotenv(dotenv);
  await writeFile(dotenvPath, text, "utf8");

  const count = Object.keys(dotenv).length;
  const bytes = Buffer.byteLength(text, "utf8");
  if (bytes > DOTENV_MAX_BYTES || count > DOTENV_MAX_VARIABLES) {
    const message = `${dotenvPath} has ${count} variables and ${bytes} bytes; GitLab accepts at most ${DOTENV_MAX_VARIABLES} variables and ${DOTENV_MAX_BYTES / 1024} KB in a dotenv report`;
    if (options.report) log.warn(message);
    else log.debug(message);
  }
}

export interface FinishOptions {
  json?: boolean | undefined;
  ci?: boolean | undefined;
  /** Stdout carries the command's own data (`plan`): the summary always goes to stderr. */
  summaryToStderr?: boolean;
}

/** Write the CI files and print the job summary (after the result lines, a blank line apart). */
export async function finishCi(
  io: CliIo,
  log: Logger,
  command: string,
  result: FlowResult,
  context: FlowContext,
  opts: FinishOptions,
): Promise<void> {
  if (!ciEnabled(io, opts)) return;
  await writeCiFiles(io, log, outputsFor(command, result, context), result.env, {
    report: DOTENV_REPORT_COMMANDS.has(command),
  });
  const summary = result.summary.trim();
  if (summary === "") return;
  const toStderr = opts.json || opts.summaryToStderr;
  const hasLines = result.lines.length > 0 && !(opts.json && result.ok);
  const text = `${hasLines ? "\n" : ""}${summary}\n`;
  if (toStderr) io.stderr(text);
  else io.stdout(text);
}

/** `emit` plus the `--ci` output. */
export async function emitCi(
  io: CliIo,
  log: Logger,
  command: string,
  result: FlowResult,
  context: FlowContext,
  opts: GlobalOpts,
): Promise<number> {
  const code = emit(io, result, { json: opts.json });
  await finishCi(io, log, command, result, context, opts);
  return code;
}

// ---------------------------------------------------------------------------
// The GitLab child pipeline

export interface ChildPipelineRequest {
  plan: Plan | undefined;
  kind: "release" | "preview";
  /** Why nothing is built (a skipped preview). */
  reason?: string;
}

/**
 * The child pipeline for a plan, after checking `.gitlab/launchset-targets.yml` and the
 * `gitlab.include` files (at the git top level: `include: local` paths are relative to the
 * repository root). Warnings about the target jobs go to the log. The plan job is the job
 * running this (`CI_JOB_NAME`); `LAUNCHSET_CLI` is passed on to the child's jobs.
 */
export async function childPipelineFor(
  io: CliIo,
  context: FlowContext,
  request: ChildPipelineRequest,
): Promise<string> {
  const root = await context.git.topLevel().catch(() => context.cwd);
  const { plan } = request;
  const builds = plan && plan.mode !== "release-pr" && plan.mode !== "none" ? plan.matrix : [];
  const read = async (path: string) => {
    const file = join(root, path);
    return existsSync(file) ? await readFile(file, "utf8") : undefined;
  };
  const { include } = gitlabSettings(context.config);
  const includes = [];
  for (const path of include) includes.push({ path, text: await read(path) });
  const { warnings, notInterruptible } = inspectTargetJobs({
    targetsText: await read(DEFAULT_TARGETS_FILE),
    includes,
    matrix: builds,
    kind: request.kind,
  });
  for (const warning of warnings) context.log.warn(warning);
  const targets: Record<string, ChildTarget> = {};
  for (const name of builds) {
    const target = context.config.targets[name];
    targets[name] = {
      ...(target ? { shell: targetShell(target) } : {}),
      ...(target?.after?.length ? { after: target.after } : {}),
      ...(notInterruptible.has(name) ? { notInterruptible: true } : {}),
    };
  }
  const currentSha = context.ci.sha ?? (await context.git.headSha().catch(() => undefined));
  return renderChildPipeline({
    plan,
    kind: request.kind,
    planJob: io.env.CI_JOB_NAME?.trim() || PLAN_JOBS[request.kind],
    includes: include,
    targets,
    ...(currentSha ? { currentSha } : {}),
    ...(io.env.LAUNCHSET_CLI?.trim() ? { cliSpec: io.env.LAUNCHSET_CLI.trim() } : {}),
    ...(request.reason ? { reason: request.reason } : {}),
  });
}

/** Print the child pipeline to the job log (a collapsed section in GitLab CI). */
function printChild(io: CliIo, file: string, content: string): void {
  if (io.env.GITLAB_CI === "true") {
    const time = Math.floor((io.now ?? new Date()).getTime() / 1000);
    io.stderr(
      `\u001b[0Ksection_start:${time}:launchset_child[collapsed=true]\r\u001b[0KChild pipeline ${file}\n${content}\u001b[0Ksection_end:${time}:launchset_child\r\u001b[0K\n`,
    );
    return;
  }
  io.stderr(`Child pipeline ${file}:\n${content}`);
}

/**
 * `--ci` on GitLab: write the child pipeline (`LAUNCHSET_CHILD_PIPELINE`, default
 * launchset-child.yml) for `release` and `preview-plan`, always (with nothing to build it has
 * one job saying why), and print it to the log.
 */
export async function writeChildPipeline(
  io: CliIo,
  context: FlowContext,
  request: ChildPipelineRequest,
  opts: { ci?: boolean | undefined },
): Promise<void> {
  if (!ciEnabled(io, opts) || context.host !== "gitlab") return;
  const content = await childPipelineFor(io, context, request);
  await writeFile(ciFilePath(io, "child"), content, "utf8");
  printChild(io, ciFileName(io, "child"), content);
}
