/**
 * `--ci` output mode: a CI runner without `@actions/core` gets a command's outputs and exported
 * variables as files. `plan.json` holds the plan, `launchset.env` is a GitLab dotenv report
 * (`artifacts:reports:dotenv`), `launchset.sh` is the same variables for `. ./launchset.sh` and
 * `launchset.ps1` for `. ./launchset.ps1` (PowerShell runners). Several commands in one job merge
 * into the same files. The pure helpers come first.
 */

